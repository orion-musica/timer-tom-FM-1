def main(out_png):
    lines = []
    for name, rows in ICONS:
        assert len(rows) == 16, name
        words = []
        for r in rows:
            assert len(r) == 16, (name, r)
            v = 0
            for i, c in enumerate(r):
                if c == "#":
                    v |= 1 << (15 - i)
            words.append("0x%04x" % v)
        lines.append("    {%s}, /* %s */" % (", ".join(words), name))
    print("static const uint16_t kt_icons[KT_ICONS][16] = {")
    print("\n".join(lines))
    print("};")
    print("static const char kt_icon_names[KT_ICONS][7] = {%s};" % ", ".join('"%s"' % n for n, _ in ICONS))
    img = Image.new("RGB", (len(ICONS) * 40, 48), (199, 240, 216))
    px = img.load()
    for k, (_, rows) in enumerate(ICONS):
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == "#":
                    for dy in range(2):
                        for dx in range(2):
                            px[k * 40 + 4 + x * 2 + dx, 8 + y * 2 + dy] = (67, 82, 61)
    img = img.resize((img.width * 2, img.height * 2), Image.NEAREST)
    img.save(out_png)

main(sys.argv[1])
